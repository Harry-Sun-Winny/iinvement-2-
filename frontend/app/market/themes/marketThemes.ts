import type { CSSProperties } from "react";

// The theme catalog is user-extensible and no longer fits a hand-maintained literal union.
export type MarketThemeId = string;

export interface MarketTheme {
  id: MarketThemeId;
  nameEn: string;
  nameVi: string;
  workspaceSurface: string;
  surface: string;
  surfaceElevated: string;
  surfaceHover: string;
  border: string;
  borderStrong: string;
  textPrimary: string;
  textSecondary: string;
  textMuted: string;
  accent: string;
  accentHover: string;
  accentSoft: string;
  positive: string;
  negative: string;
  warning: string;
  info: string;
  chartGrid: string;
  chartAxis: string;
  chartCrosshair: string;
  selection: string;
  shadow: string;
  panelBg: string;
}

export type MarketThemeStyle = CSSProperties & Record<`--market-${string}`, string>;

export function getMarketThemeStyle(theme: MarketTheme): MarketThemeStyle {
  return {
    "--market-panel-bg": theme.panelBg,
    "--market-bg": theme.workspaceSurface,
    "--market-surface": theme.surface,
    "--market-surface-elevated": theme.surfaceElevated,
    "--market-surface-hover": theme.surfaceHover,
    "--market-border": theme.border,
    "--market-border-strong": theme.borderStrong,
    "--market-text-primary": theme.textPrimary,
    "--market-text-secondary": theme.textSecondary,
    "--market-text-muted": theme.textMuted,
    "--market-accent": theme.accent,
    "--market-accent-hover": theme.accentHover,
    "--market-accent-soft": theme.accentSoft,
    "--market-positive": theme.positive,
    "--market-negative": theme.negative,
    "--market-warning": theme.warning,
    "--market-info": theme.info,
    "--market-chart-grid": theme.chartGrid,
    "--market-chart-axis": theme.chartAxis,
    "--market-chart-crosshair": theme.chartCrosshair,
    "--market-selection": theme.selection,
    "--market-shadow": theme.shadow,
  };
}

